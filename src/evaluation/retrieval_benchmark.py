"""
Offline retrieval benchmark (no LLM calls, no API keys).

Compares index configurations on the project's existing question set
(``data/processed/eval_dataset.json``: 51 questions, each with the arXiv id of
the source paper and the exact text span the question was written from).

Metrics (k ∈ {1, 2, 5, 10}; mean over questions)
-----------------------------------------------
paper_hit@k       1 if any of the top-k passages comes from the gold paper.
paper_mrr         1 / rank of the first passage from the gold paper (0 if not in top 10).
evidence_recall@k fraction of the gold span's word 5-grams that occur in the union
                  of the top-k passages *as delivered to the generator*
                  (v0.1 truncated each passage to 1,200 characters; the current
                  pipeline to ``Settings.max_evidence_chars``).
evidence_hit@k    1 if evidence_recall@k ≥ 0.5.
words@k           mean number of words delivered to the generator (the context budget).
ref_noise@k       share of top-k passages that look like bibliography
                  (≥ 4 occurrences of "et al." or "arXiv preprint"; a proxy).
latency           query embedding + FAISS search, milliseconds (p50 / p95).

Known biases: the questions were generated by Gemini from randomly sampled
*v0.1 chunks*, so every gold span lies inside one v0.1 chunk (a structural
advantage for the v0.1 configuration), and all questions are single-paper and
extractive. Text is normalised (lower-case, de-hyphenated, alphanumeric
tokens) before matching, so the v0.1 text's hyphenation artefacts do not
count against either side. Latency depends on the machine and its load.

Usage::

    python -m src.evaluation.retrieval_benchmark --build      # build benchmark indexes, then evaluate
    python -m src.evaluation.retrieval_benchmark              # evaluate existing benchmark indexes
"""

from __future__ import annotations

import json
import logging
import platform
import re
import statistics
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable

import src.config as config

logger = logging.getLogger(__name__)

KS = (1, 2, 5, 10)
# The "Metrics … Known biases" part of the module docstring, reused in the Markdown report.
METRICS_DOC = "Metrics (k" + __doc__.split("Metrics (k", 1)[1].split("Usage::", 1)[0].rstrip()
BENCH_DIR = config.DATA_DIR / "benchmark"
DATASET = config.PROCESSED_DIR / "eval_dataset.json"
LEGACY_DELIVERED_CHARS = 1200  # v0.1 generator.build_context truncation


# ── Metric primitives ─────────────────────────────────────────────────────────


def tokens(text: str) -> list[str]:
    text = re.sub(r"(\w)-\s+(\w)", r"\1\2", text)  # "abili- ties" → "abilities"
    return re.findall(r"[a-z0-9]+", text.lower())


def ngrams(toks: list[str], n: int = 5) -> set[tuple[str, ...]]:
    if len(toks) < n:
        return {tuple(toks)} if toks else set()
    return {tuple(toks[i : i + n]) for i in range(len(toks) - n + 1)}


def evidence_recall(gold: str, passages: list[str]) -> float:
    gold_grams = ngrams(tokens(gold))
    if not gold_grams:
        return 0.0
    seen: set[tuple[str, ...]] = set()
    for passage in passages:
        seen |= ngrams(tokens(passage))
    return len(gold_grams & seen) / len(gold_grams)


def looks_like_bibliography(text: str) -> bool:
    return text.count("et al.") + text.count("arXiv preprint") >= 4


def reciprocal_rank(gold_paper: str, ranked_papers: list[str]) -> float:
    for rank, paper in enumerate(ranked_papers, start=1):
        if paper == gold_paper:
            return 1.0 / rank
    return 0.0


def percentile(values: list[float], q: float) -> float:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(round(q * (len(ordered) - 1))))]


@dataclass
class Config:
    name: str
    description: str
    delivered_chars: int


def evaluate(
    dataset: list[dict[str, Any]],
    search: Callable[[str, int], list[dict[str, Any]]],
    delivered_chars: int,
) -> dict[str, Any]:
    """Run every question through ``search(query, k)`` and aggregate metrics."""
    per_q: list[dict[str, Any]] = []
    latencies: list[float] = []
    max_k = max(KS)
    for item in dataset:
        started = time.perf_counter()
        results = search(item["question"], max_k)
        latencies.append((time.perf_counter() - started) * 1000)
        papers = [r["arxiv_id"] for r in results]
        delivered = [r["text"][:delivered_chars] for r in results]
        row: dict[str, Any] = {
            "question": item["question"],
            "arxiv_id": item["arxiv_id"],
            "paper_rr": reciprocal_rank(item["arxiv_id"], papers),
        }
        for k in KS:
            row[f"paper_hit@{k}"] = float(item["arxiv_id"] in papers[:k])
            row[f"evidence_recall@{k}"] = evidence_recall(item["context"], delivered[:k])
            row[f"evidence_hit@{k}"] = float(row[f"evidence_recall@{k}"] >= 0.5)
            row[f"words@{k}"] = sum(len(t.split()) for t in delivered[:k])
            row[f"ref_noise@{k}"] = (
                sum(looks_like_bibliography(r["text"]) for r in results[:k]) / k if results else 0.0
            )
        per_q.append(row)

    def mean(key: str, rows: list[dict[str, Any]] = per_q) -> float:
        return round(statistics.mean(r[key] for r in rows), 4) if rows else float("nan")

    summary: dict[str, Any] = {"n": len(per_q), "paper_mrr": mean("paper_rr")}
    for k in KS:
        for metric in ("paper_hit", "evidence_recall", "evidence_hit", "words", "ref_noise"):
            summary[f"{metric}@{k}"] = mean(f"{metric}@{k}")
    summary["latency_ms_p50"] = round(percentile(latencies, 0.5), 2)
    summary["latency_ms_p95"] = round(percentile(latencies, 0.95), 2)
    return {"summary": summary, "per_question": per_q}


# ── Index construction for the compared configurations ───────────────────────


def legacy_chunks() -> list[dict[str, Any]]:
    """v0.1 chunks exactly as committed in ``data/processed/chunks`` (embedded without headers)."""
    from src.utils.metadata_utils import load_metadata

    metadata = load_metadata(config.META_FILE)
    chunks = []
    for path in sorted(config.CHUNK_DIR.glob("*_chunks.json")):
        arxiv_id = path.name[: -len("_chunks.json")]
        if arxiv_id not in metadata:
            continue
        paper = metadata[arxiv_id]
        for c in json.loads(path.read_text(encoding="utf-8")):
            chunks.append(
                {
                    **c,
                    "title": paper.get("title", ""),
                    "url": paper.get("url", ""),
                    "published": paper.get("published", ""),
                    "authors": paper.get("authors", []),
                    "section": "",
                    "heading": "",
                    "page_start": None,
                    "page_end": None,
                    "content_hash": f"{c['chunk_id']}",
                    "source_format": "legacy",
                }
            )
    return chunks


CONFIGS = {
    "v01_legacy": Config("v01_legacy", "v0.1 chunks (sentence regex, ~535 words), raw text embedded", LEGACY_DELIVERED_CHARS),
    "v02_text": Config("v02_text", "new chunker on the v0.1 .txt files (no PDFs), contextual headers", 0),
    "v02_pdf": Config("v02_pdf", "structured PDF parse + new chunker, contextual headers", 0),
    "v02_pdf_noheader": Config("v02_pdf_noheader", "structured PDF parse + new chunker, no contextual headers", 0),
}


def build_benchmark_indexes(names: list[str]) -> dict[str, dict[str, Any]]:
    from src.ingestion.chunker import chunk_corpus
    from src.utils.metadata_utils import load_metadata
    from src.vectorstore.faiss_store import build_index

    base = config.get_settings()
    metadata = load_metadata(config.META_FILE)
    manifests = {}
    for name in names:
        if name == "v01_legacy":
            chunks, settings = legacy_chunks(), base.model_copy(update={"contextual_headers": False})
        else:
            settings = base.model_copy(update={"contextual_headers": name != "v02_pdf_noheader"})
            chunks, stats = chunk_corpus(metadata, settings, prefer_pdf=name != "v02_text")
            logger.info("%s chunking: %s", name, stats)
        manifests[name] = build_index(chunks, BENCH_DIR / name, settings=settings)
    return manifests


def run(names: list[str], dataset_path: Path = DATASET) -> dict[str, Any]:
    from src.vectorstore.faiss_store import FAISSStore

    dataset = json.loads(dataset_path.read_text(encoding="utf-8"))
    max_chars = config.get_settings().max_evidence_chars
    report: dict[str, Any] = {
        "dataset": str(dataset_path.relative_to(config.PROJECT_ROOT)),
        "questions": len(dataset),
        "environment": {"python": platform.python_version(), "machine": platform.machine()},
        "configs": {},
    }
    for name in names:
        store = FAISSStore(index_dir=BENCH_DIR / name)
        store.search("warm-up query", top_k=1)
        cfg = CONFIGS[name]
        result = evaluate(dataset, lambda q, k: store.search(q, top_k=k), cfg.delivered_chars or max_chars)
        report["configs"][name] = {
            "description": cfg.description,
            "index": {k: store.manifest.get(k) for k in ("embedding_model", "num_vectors", "num_papers", "source_formats", "chunking", "contextual_headers")},
            **result,
        }
    return report


def to_markdown(report: dict[str, Any]) -> str:
    names = list(report["configs"])
    rows = [
        ("paper_hit@1", "Paper hit@1"),
        ("paper_hit@2", "Paper hit@2"),
        ("paper_hit@5", "Paper hit@5"),
        ("paper_mrr", "Paper MRR@10"),
        ("evidence_recall@2", "Evidence recall@2"),
        ("evidence_recall@5", "Evidence recall@5"),
        ("evidence_recall@10", "Evidence recall@10"),
        ("evidence_hit@2", "Evidence hit@2"),
        ("evidence_hit@5", "Evidence hit@5"),
        ("words@2", "Words delivered @2"),
        ("words@5", "Words delivered @5"),
        ("ref_noise@5", "Bibliography share @5"),
        ("latency_ms_p50", "Search latency p50 (ms)"),
        ("latency_ms_p95", "Search latency p95 (ms)"),
    ]
    out = [
        "| Metric | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for key, label in rows:
        vals = [report["configs"][n]["summary"].get(key) for n in names]
        out.append(f"| {label} | " + " | ".join(f"{v:.3f}" if isinstance(v, float) and v < 50 else f"{v:,.1f}" if isinstance(v, float) else str(v) for v in vals) + " |")
    out.append("")
    out.append("| Config | Description | Vectors | Papers |")
    out.append("|---|---|---|---|")
    for n in names:
        c = report["configs"][n]
        out.append(f"| {n} | {c['description']} | {c['index']['num_vectors']:,} | {c['index']['num_papers']} |")
    return "\n".join(out)


def main() -> None:
    import argparse

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--build", action="store_true", help="(re)build the benchmark indexes first")
    ap.add_argument("--configs", nargs="+", default=list(CONFIGS), choices=list(CONFIGS))
    ap.add_argument("--out", type=Path, default=config.REPORTS_DIR / "retrieval_benchmark.json")
    args = ap.parse_args()
    if args.build:
        build_benchmark_indexes(args.configs)
    report = run(args.configs)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2), encoding="utf-8")
    table = to_markdown(report)
    args.out.with_suffix(".md").write_text(
        "# Retrieval benchmark\n\n"
        f"Generated by `python -m src.evaluation.retrieval_benchmark` on {report['questions']} questions from "
        f"`{report['dataset']}` (Python {report['environment']['python']}, CPU). "
        "All configurations use the same embedding model (all-MiniLM-L6-v2) and the same questions; "
        "no LLM is involved. Per-question results are in `retrieval_benchmark.json`.\n\n"
        + table
        + "\n\n## Metric definitions and caveats\n\n"
        + "```text\n"
        + METRICS_DOC
        + "\n```\n",
        encoding="utf-8",
    )
    print(table)


if __name__ == "__main__":
    main()
